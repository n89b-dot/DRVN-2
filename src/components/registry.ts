/**
 * The DRVN component registry — the machine-readable source of truth for the
 * reusable component system.
 *
 * Every public PascalCase export from the shared entry points
 * (`@/components/ui`, `@/components/commerce`, `@/components/livesheet`) must
 * have an entry here, and every entry must resolve to a real export —
 * enforced by `registry.test.ts`. The `/docs/components` inventory and the
 * generated section of `docs/site/components.md` render from this data, so
 * code and documentation cannot silently drift apart.
 *
 * Layers:
 * - `primitive` — generic Livesheet visual/interaction contracts (product-agnostic).
 * - `pattern`   — DRVN domain patterns (know listings, orders, vehicles…).
 * - `feature`   — business workflows documented for discoverability; they live
 *   with their route/feature and are NOT exported from a shared entry point.
 */

export type RegistryLayer = "primitive" | "pattern" | "feature";
export type RegistryStatus = "active" | "deprecated" | "internal";

export type RegistryEntry = {
  /** Exported symbol name. */
  name: string;
  /** Where to import it from (features: their own module path). */
  importPath: string;
  /** Repo-relative source file (used by the resolution test). */
  file: string;
  layer: RegistryLayer;
  category:
    | "foundation"
    | "navigation"
    | "action"
    | "form"
    | "card"
    | "row"
    | "data"
    | "status"
    | "feedback"
    | "overlay"
    | "media"
    | "messaging"
    | "social"
    | "profile"
    | "commerce"
    | "motion"
    | "loading";
  status: RegistryStatus;
  description: string;
  /** When to reach for it. */
  use: string;
  /** When NOT to use it / what to use instead. */
  avoid?: string;
  variants?: string[];
  states?: string[];
  /** The Livesheet CSS recipe it emits, when it owns one. */
  cssRecipe?: string;
  a11y?: string;
  responsive?: string;
};

