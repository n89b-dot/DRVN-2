/** Plain code-unit order, so the result does not depend on any database or system collation. */
export const byText = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const sortBy = (list, key) => [...list].sort((a, b) => byText(key(a), key(b)));

const ident = (name) => (/^[a-z_][a-z0-9_]*$/.test(name) ? name : `"${name.replace(/"/g, '""')}"`);
const qname = (schema, name) => `${ident(schema)}.${ident(name)}`;
const literal = (text) => `'${String(text).replace(/'/g, "''")}'`;

/** A file-name-safe form of an object name. Anything unusual gets a short hash so two names never share a file. */
export function slug(name) {
  const safe = name.toLowerCase().replace(/[^a-z0-9_]+/g, "_").replace(/^_+|_+$/g, "");
  if (safe === name && safe.length <= 80) return safe;
  const hash = createHash("sha256").update(name).digest("hex").slice(0, 8);
  return `${safe.slice(0, 60) || "x"}-${hash}`;
}

const TABLE_PRIVILEGES = ["delete", "insert", "maintain", "references", "select", "trigger", "truncate", "update"];

/**
 * Grant lines for an object. `acl` is [{grantee, privilege, grantable}] with
 * the platform administrators already removed. Privileges are grouped per
 * grantee, in a fixed order; a full table set reads `all`.
 */
export function grantLines(acl, target, { fullSet = null } = {}) {
  const groups = new Map();
  for (const item of acl ?? []) {
    const key = `${item.grantee}\u0000${item.grantable ? 1 : 0}`;
    if (!groups.has(key)) groups.set(key, { grantee: item.grantee, grantable: item.grantable, privileges: [] });
    groups.get(key).privileges.push(item.privilege);
  }
  const lines = [];
  for (const group of sortBy([...groups.values()], (g) => `${g.grantee}\u0000${g.grantable ? 1 : 0}`)) {
    const privileges = [...new Set(group.privileges)].sort(byText);
    const text = fullSet && fullSet.every((p) => privileges.includes(p)) && privileges.length === fullSet.length ? "all" : privileges.join(", ");
    lines.push(`grant ${text} on ${target} to ${ident(group.grantee)}${group.grantable ? " with grant option" : ""};`);
  }
  return lines;
}

/** Column grants, grouped so one line names every column a role holds a privilege on. */
function columnGrantLines(columns, target) {
  const groups = new Map();
  for (const column of columns) {
    for (const item of column.acl ?? []) {
      const key = `${item.grantee}\u0000${item.privilege}\u0000${item.grantable ? 1 : 0}`;
      if (!groups.has(key)) groups.set(key, { ...item, columns: [] });
      groups.get(key).columns.push(column.name);
    }
  }
  return sortBy([...groups.values()], (g) => `${g.grantee}\u0000${g.privilege}\u0000${g.grantable ? 1 : 0}`).map(
    (g) => `grant ${g.privilege} (${g.columns.map(ident).join(", ")}) on table ${target} to ${ident(g.grantee)}${g.grantable ? " with grant option" : ""};`,
  );
}

function section(title, lines) {
  return lines.length ? `\n-- ${title}\n${lines.join("\n")}\n` : "";
}

function renderFunctionFile(overloads) {
  const parts = [HEADER];
  for (const fn of sortBy(overloads, (f) => f.identity)) {
    const signature = `${qname(fn.schema, fn.name)}(${fn.identity})`;
    parts.push(`\n${fn.def.replace(/\s+$/, "")};\n`);
    if (fn.comment != null) parts.push(`\ncomment on function ${signature} is ${literal(fn.comment)};\n`);
    const grants = grantLines(fn.acl, `function ${signature}`);
    parts.push(grants.length ? `\n${grants.join("\n")}\n` : `\n-- No role is granted execute on ${signature}.\n`);
  }
  return parts.join("");
}

function renderTable(table) {
  const name = qname(table.schema, table.name);
  const columns = table.columns.map((c) => {
    let line = `  ${ident(c.name)} ${c.type}`;
    if (c.collation) line += ` collate ${c.collation}`;
    if (c.generated === "s") line += ` generated always as (${c.default}) stored`;
    else if (c.identity === "a") line += " generated always as identity";
    else if (c.identity === "d") line += " generated by default as identity";
    else if (c.default != null) line += ` default ${c.default}`;
    if (c.notnull) line += " not null";
    return line;
  });
  const out = [HEADER, `\ncreate ${table.unlogged ? "unlogged " : ""}table ${name} (\n${columns.join(",\n")}\n)`];
  out.push(table.options?.length ? ` with (${[...table.options].sort(byText).join(", ")});\n` : ";\n");
  const settings = [];
  if (table.rls) settings.push(`alter table ${name} enable row level security;`);
  if (table.force_rls) settings.push(`alter table ${name} force row level security;`);
  if (table.replica_identity !== "d") {
    const mode = { n: "nothing", f: "full", i: "using index" }[table.replica_identity] ?? table.replica_identity;
    settings.push(`alter table ${name} replica identity ${mode};`);
  }
  if (settings.length) out.push(`\n${settings.join("\n")}\n`);
  const comments = [];
  if (table.comment != null) comments.push(`comment on table ${name} is ${literal(table.comment)};`);
  for (const c of table.columns) if (c.comment != null) comments.push(`comment on column ${name}.${ident(c.name)} is ${literal(c.comment)};`);
  out.push(section("Comments", comments));
  const constraints = [];
  for (const c of sortBy(table.constraints, (x) => x.name)) {
    constraints.push(`alter table ${name} add constraint ${ident(c.name)} ${c.def};`);
    if (c.comment != null) constraints.push(`comment on constraint ${ident(c.name)} on ${name} is ${literal(c.comment)};`);
  }
  out.push(section("Constraints", constraints));
  const indexes = [];
  for (const i of sortBy(table.indexes, (x) => x.name)) {
    indexes.push(`${i.def};${i.valid ? "" : " -- NOT VALID: the build that made it did not finish"}`);
    if (i.comment != null) indexes.push(`comment on index ${qname(table.schema, i.name)} is ${literal(i.comment)};`);
  }
  out.push(section("Indexes", indexes));
  const grants = [...grantLines(table.acl, `table ${name}`, { fullSet: TABLE_PRIVILEGES }), ...columnGrantLines(table.columns, name)];
  out.push(grants.length ? section("Grants", grants) : `\n-- Grants: none. No role but the owner and the administrators can touch this table.\n`);
  return out.join("");
}

function renderView(view) {
  const name = qname(view.schema, view.name);
  const out = [HEADER, `\ncreate view ${name}${view.options?.length ? ` with (${[...view.options].sort(byText).join(", ")})` : ""} as\n${view.def.replace(/\s+$/, "")}\n`];
  if (view.comment != null) out.push(`\ncomment on view ${name} is ${literal(view.comment)};\n`);
  const grants = grantLines(view.acl, `table ${name}`, { fullSet: TABLE_PRIVILEGES });
  out.push(grants.length ? section("Grants", grants) : "\n-- Grants: none.\n");
  return out.join("");
}

function renderType(type) {
  const name = qname(type.schema, type.name);
  const out = [HEADER];
  if (type.kind === "e") out.push(`\ncreate type ${name} as enum (\n${type.labels.map((l) => `  ${literal(l)}`).join(",\n")}\n);\n`);
  else if (type.kind === "d") {
    out.push(`\ncreate domain ${name} as ${type.base}${type.default != null ? ` default ${type.default}` : ""}${type.notnull ? " not null" : ""}`);
    for (const c of sortBy(type.constraints ?? [], (x) => x.name)) out.push(`\n  constraint ${ident(c.name)} ${c.def}`);
    out.push(";\n");
  } else out.push(`\ncreate type ${name} as (\n${(type.attributes ?? []).map((a) => `  ${ident(a.name)} ${a.type}`).join(",\n")}\n);\n`);
  if (type.comment != null) out.push(`\ncomment on type ${name} is ${literal(type.comment)};\n`);
  out.push(section("Grants", grantLines(type.acl, `type ${name}`)));
  return out.join("");
}

function renderTrigger(trigger) {
  const table = qname(trigger.schema, trigger.table);
  const out = [HEADER, `\n${trigger.def};\n`];
  const state = { D: "disable", R: "enable replica", A: "enable always" }[trigger.enabled];
  if (state) out.push(`\nalter table ${table} ${state} trigger ${ident(trigger.name)};\n`);
  if (trigger.comment != null) out.push(`\ncomment on trigger ${ident(trigger.name)} on ${table} is ${literal(trigger.comment)};\n`);
  return out.join("");
}

function renderPolicy(policy) {
  const table = qname(policy.schema, policy.table);
  const lines = [`create policy ${ident(policy.name)} on ${table}`, `  as ${policy.permissive ? "permissive" : "restrictive"}`, `  for ${policy.command}`, `  to ${[...policy.roles].sort(byText).map(ident).join(", ")}`];
  if (policy.using != null) lines.push(`  using (${policy.using})`);
  if (policy.check != null) lines.push(`  with check (${policy.check})`);
  const out = [HEADER, `\n${lines.join("\n")};\n`];
  if (policy.comment != null) out.push(`\ncomment on policy ${ident(policy.name)} on ${table} is ${literal(policy.comment)};\n`);
  return out.join("");
}

