#!/usr/bin/env node
// Plan 2 item A1 (review finding #159): the database as it stands, checked in.
//
// The migrations are a history: to change one line of a function the whole
// function is copied into a new file, so nobody can read what a function is
// today or see the line that changed. This writes the current state of a
// freshly built database under supabase/schema/, one file per function,
// table, view, trigger and policy, plus the things a plain schema dump leaves
// out (scheduled jobs, storage buckets and rules, roles, default privileges,
// publications, and the rows migrations insert).
//
//   npm run db:schema            write supabase/schema/ from the database
//   npm run db:schema -- --check compare, and exit 1 if the folder is stale
//
// The database must be the disposable one the sql-guard job builds:
// supabase/tests/ci_shim.sql, then every file in supabase/migrations/, applied
// as supabase_admin on the pinned supabase/postgres image, and nothing run
// against it since (scripts/disposable-db.sh builds exactly that). The output
// has no timestamps, owners, grantors, oids or versions in it, so two builds of
// the same migrations give byte-identical folders.
//
// It needs only psql and Node: no npm install, so the sql-guard job runs it.
