/**
 * Every file of the snapshot, as a Map of relative path to content.
 * `doc` is the JSON scripts/schema-snapshot.sql returns; `rows` maps each
 * reference table to its rows.
 */
export function renderSnapshot(doc, rows = {}) {
  const unsupported = Object.entries(doc.unsupported ?? {}).filter(([, n]) => Number(n) > 0);
  if (unsupported.length) {
    throw new Error(
      `The database has objects the snapshot does not render: ${unsupported.map(([k, n]) => `${n} ${k}`).join(", ")}. ` +
        "Teach scripts/schema-snapshot.sql and .mjs to write them before adding them, or the snapshot would silently leave them out.",
    );
  }
  const unclassed = Object.keys(doc.row_counts ?? {}).filter((t) => !(t in REFERENCE_TABLES) && !(t in RUN_LOG_TABLES)).sort(byText);
  if (unclassed.length) {
    throw new Error(
      `These tables hold rows in a freshly built database but are not classed: ${unclassed.join(", ")}. ` +
        "If a migration inserts them as reference data, add the table to REFERENCE_TABLES in scripts/schema-snapshot.mjs. " +
        "If the database is not fresh (SQL guards or an app have run against it), rebuild it: bash scripts/disposable-db.sh start.",
    );
  }

  const files = new Map();
  const taken = new Map();
  const put = (file, content) => {
    const key = file.toLowerCase();
    if (taken.has(key)) throw new Error(`Two objects map to the same snapshot file: ${file} (${taken.get(key)})`);
    taken.set(key, file);
    files.set(file, content.endsWith("\n") ? content : `${content}\n`);
  };

  put("README.md", README);

  put("schemas.sql", HEADER + sortBy(doc.schemas, (s) => s.name).map((s) =>
    `\ncreate schema if not exists ${ident(s.name)};\n` +
    (s.comment != null ? `comment on schema ${ident(s.name)} is ${literal(s.comment)};\n` : "") +
    (grantLines(s.acl, `schema ${ident(s.name)}`).join("\n") || `-- Grants: none.`) + "\n").join(""));

  put("extensions.sql", HEADER + "\n" + sortBy(doc.extensions, (e) => e.name).map((e) => `create extension if not exists ${ident(e.name)} with schema ${ident(e.schema)};`).join("\n") + "\n");

  put("roles.sql", HEADER + "-- Roles a migration created. The Supabase platform's own roles are not listed.\n" + sortBy(doc.roles, (r) => r.name).map((r) => {
    const attributes = [r.login ? "login" : "nologin", r.inherit ? "inherit" : "noinherit", r.superuser ? "superuser" : null, r.createrole ? "createrole" : null,
      r.createdb ? "createdb" : null, r.replication ? "replication" : null, r.bypassrls ? "bypassrls" : null,
      r.connection_limit !== -1 ? `connection limit ${r.connection_limit}` : null].filter(Boolean);
    const lines = [`\ncreate role ${ident(r.name)} ${attributes.join(" ")};`];
    for (const setting of [...(r.config ?? [])].sort(byText)) lines.push(`alter role ${ident(r.name)} set ${setting};`);
    for (const parent of r.member_of) lines.push(`grant ${ident(parent)} to ${ident(r.name)};`);
    for (const member of r.members) lines.push(`grant ${ident(r.name)} to ${ident(member)};`);
    return lines.join("\n") + "\n";
  }).join(""));

  put("role-settings.sql", HEADER + "-- alter role … set and alter database … set, platform roles included.\n\n" +
    sortBy(doc.settings, (s) => `${s.database ?? ""}\u0000${s.role ?? ""}`).flatMap((s) =>
      [...(s.config ?? [])].sort(byText).map((c) => `alter ${s.role ? `role ${ident(s.role)}` : "database"}${s.database ? ` in database ${ident(s.database)}` : ""} set ${c};`)).join("\n") + "\n");

  put("default-privileges.sql", HEADER + "-- What an object created by each role is granted before any migration says otherwise.\n-- CI builds as supabase_admin; a hosted project's migrations run as postgres.\n\n" +
    sortBy(doc.default_privileges, (d) => `${d.role}\u0000${d.schema ?? ""}\u0000${d.objects}`).flatMap((d) => {
      const target = `alter default privileges for role ${ident(d.role)}${d.schema ? ` in schema ${ident(d.schema)}` : ""}`;
      const lines = grantLines(d.acl, d.objects, { fullSet: d.objects === "tables" ? TABLE_PRIVILEGES : null }).map((l) => `${target} ${l}`);
      return lines.length ? lines : [`${target}: nothing is granted on ${d.objects}.`];
    }).join("\n") + "\n");

  put("publications.sql", HEADER + "\n" + sortBy(doc.publications, (p) => `${p.publication}\u0000${p.schema}\u0000${p.table}`).map((p) =>
    `alter publication ${ident(p.publication)} add table ${qname(p.schema, p.table)}${p.columns ? ` (${p.columns.map(ident).join(", ")})` : ""}${p.where ? ` where (${p.where})` : ""};`).join("\n") + "\n");

  put("cron-jobs.sql", HEADER + "-- Scheduled jobs (pg_cron). One statement per job.\n\n" + sortBy(doc.cron_jobs, (j) => j.name).map((j) =>
    `select cron.schedule(${literal(j.name)}, ${literal(j.schedule)}, ${literal(j.command)});${j.active ? "" : " -- inactive"}`).join("\n") + "\n");

  put("storage-buckets.sql", HEADER + "\n" + sortBy(doc.storage_buckets, (b) => b.id).map((b) =>
    `insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (${literal(b.id)}, ${literal(b.name)}, ${b.public}, ${b.file_size_limit ?? "null"}, ${
      b.allowed_mime_types ? `array[${b.allowed_mime_types.map(literal).join(", ")}]` : "null"});`).join("\n") + "\n");

  put("sequences.sql", HEADER + "\n" + sortBy(doc.sequences, (s) => `${s.schema}.${s.name}`).map((s) => {
    const lines = [`create sequence ${qname(s.schema, s.name)} as ${s.type} start ${s.start} increment ${s.increment} minvalue ${s.min} maxvalue ${s.max} cache ${s.cache}${s.cycle ? " cycle" : ""}${s.owned_by ? ` owned by ${s.owned_by}` : ""};`];
    lines.push(...grantLines(s.acl, `sequence ${qname(s.schema, s.name)}`));
    return lines.join("\n");
  }).join("\n") + "\n");

  for (const type of doc.types) put(`types/${slug(type.schema)}.${slug(type.name)}.sql`, renderType(type));
  for (const table of doc.tables) put(`tables/${slug(table.schema)}.${slug(table.name)}.sql`, renderTable(table));
  for (const view of doc.views) put(`views/${slug(view.schema)}.${slug(view.name)}.sql`, renderView(view));

  const byName = new Map();
  for (const fn of doc.functions) {
    const key = `${fn.schema}\u0000${fn.name}`;
    if (!byName.has(key)) byName.set(key, []);
    byName.get(key).push(fn);
  }
  for (const overloads of byName.values()) put(`functions/${slug(overloads[0].schema)}.${slug(overloads[0].name)}.sql`, renderFunctionFile(overloads));

  for (const trigger of doc.triggers) put(`triggers/${slug(trigger.schema)}.${slug(trigger.table)}.${slug(trigger.name)}.sql`, renderTrigger(trigger));
  for (const policy of doc.policies) put(`policies/${slug(policy.schema)}.${slug(policy.table)}.${slug(policy.name)}.sql`, renderPolicy(policy));

  for (const table of Object.keys(REFERENCE_TABLES).sort(byText)) {
    const list = (rows[table] ?? []).map((row) => JSON.stringify(row)).sort(byText);
    const [schema, name] = table.split(".");
    put(`reference-data/${slug(schema)}.${slug(name)}.jsonl`, list.length ? list.join("\n") + "\n" : "\n");
  }
  return files;
}

/** The query that reads every reference table's rows, minus its omitted columns, as one JSON object. */
export function referenceRowsSql() {
  const parts = Object.entries(REFERENCE_TABLES).map(([table, { omit }]) => {
    const [schema, name] = table.split(".");
    const omitted = omit.length ? ` - array[${omit.map(literal).join(", ")}]::text[]` : "";
    return `${literal(table)}, (select coalesce(jsonb_agg(to_jsonb(t)${omitted}), '[]'::jsonb) from ${qname(schema, name)} t)`;
  });
  return `select jsonb_build_object(${parts.join(",\n  ")})::text;`;
}

/** What differs between the snapshot on disk and the generated one. */
export function compareSnapshot(generated, readFile, listFiles) {
  const onDisk = new Set(listFiles());
  const problems = { missing: [], extra: [], changed: [] };
  for (const [file, content] of generated) {
    if (!onDisk.has(file)) problems.missing.push(file);
    else if (readFile(file) !== content) problems.changed.push(file);
  }
  for (const file of onDisk) if (!generated.has(file)) problems.extra.push(file);
  for (const list of Object.values(problems)) list.sort(byText);
  return problems;
}

function listTree(dir, base = dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? listTree(full, base) : [path.relative(base, full).split(path.sep).join("/")];
  });
}

function writeTree(dir, files) {
  for (const stale of listTree(dir)) if (!files.has(stale)) fs.rmSync(path.join(dir, stale));
  for (const [file, content] of files) {
    const full = path.join(dir, file);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    if (!fs.existsSync(full) || fs.readFileSync(full, "utf8") !== content) fs.writeFileSync(full, content);
  }
  // Remove folders the snapshot no longer uses.
  const prune = (d) => {
    for (const entry of fs.readdirSync(d, { withFileTypes: true })) if (entry.isDirectory()) prune(path.join(d, entry.name));
    if (d !== dir && fs.readdirSync(d).length === 0) fs.rmdirSync(d);
  };
  if (fs.existsSync(dir)) prune(dir);
}

/**
 * @param {string} databaseUrl
 * @param {Record<string, string | undefined>} [env]
 */
export function assertDisposable(databaseUrl, env = process.env) {
  const target = new URL(databaseUrl);
  const local = ["127.0.0.1", "localhost"].includes(target.hostname);
  const allowed = ALLOWED_PORTS.includes(target.port) || (target.port === "5432" && env.CI === "true");
  if (!local || !allowed) {
    throw new Error(
      `The schema snapshot reads only the disposable database (127.0.0.1 on ${ALLOWED_PORTS.join(", ")}, or 5432 in CI), not ${target.hostname}:${target.port}. ` +
        "A `supabase start` database (54322) is built differently and would give a different snapshot.",
    );
  }
}

function psql(databaseUrl, args) {
  return execFileSync("psql", [databaseUrl, "-X", "-At", "-q", "-v", "ON_ERROR_STOP=1", ...args], { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });
}

function main() {
  const check = process.argv.includes("--check");
  const databaseUrl = process.env.DRVN_SCHEMA_DATABASE_URL || "postgresql://supabase_admin:postgres@127.0.0.1:55440/postgres";
  assertDisposable(databaseUrl);
  const doc = JSON.parse(psql(databaseUrl, ["-f", path.join(here, "schema-snapshot.sql")]).trim().split("\n").pop());
  const rows = JSON.parse(psql(databaseUrl, ["-c", referenceRowsSql()]).trim());
  const files = renderSnapshot(doc, rows);
  const counts = `${doc.functions.length} functions, ${doc.tables.length} tables, ${doc.policies.length} policies, ${doc.triggers.length} triggers, ${doc.cron_jobs.length} scheduled jobs`;

  if (!check) {
    writeTree(SCHEMA_DIR, files);
    console.log(`Wrote ${files.size} files to ${SCHEMA_DIR}/ (${counts}).`);
    return;
  }

  const problems = compareSnapshot(files, (file) => fs.readFileSync(path.join(SCHEMA_DIR, file), "utf8"), () => listTree(SCHEMA_DIR));
  const total = problems.missing.length + problems.extra.length + problems.changed.length;
  if (total === 0) {
    console.log(`${SCHEMA_DIR}/ matches the database (${files.size} files; ${counts}).`);
    return;
  }
  // Keep what the generator produced, so a branch can take it as it is.
  const out = process.env.DRVN_SCHEMA_MISMATCH_OUT || fs.mkdtempSync(path.join(os.tmpdir(), "drvn-schema-"));
  writeTree(out, files);
  const show = (label, list) => (list.length ? `\n${label} (${list.length}):\n${list.slice(0, 40).map((f) => `  ${f}`).join("\n")}${list.length > 40 ? `\n  … and ${list.length - 40} more` : ""}` : "");
  console.error(
    `${SCHEMA_DIR}/ is out of date: ${total} file${total === 1 ? " differs" : "s differ"} from the database the migrations build.` +
      show("Changed", problems.changed) + show("Missing from the folder", problems.missing) + show("In the folder but not in the database", problems.extra),
  );
  for (const file of problems.changed.slice(0, 5)) {
    const diff = spawnSync("diff", ["-u", path.join(SCHEMA_DIR, file), path.join(out, file)], { encoding: "utf8" });
    console.error(`\n${(diff.stdout ?? "").split("\n").slice(0, 60).join("\n")}`);
  }
  console.error(`\nRegenerate with \`npm run db:schema\` and commit the result (the generated folder is at ${out}; in CI it is the schema-snapshot artifact).`);
  process.exit(1);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (error) {
    console.error(`schema snapshot: ${error instanceof Error ? error.message : error}`);
    process.exit(1);
  }
}
