// Tables that hold rows in a database nobody has used, because a migration
// inserted them. Their rows are part of the schema's meaning (a setting, a
// switch, a reserved name), so the snapshot carries them. `omit` lists the
// columns a default fills in at insert time (a clock or a random id), which
// differ on every build and mean nothing.
export const REFERENCE_TABLES = {
  "private.reserved_usernames": { omit: [] },
  "public.agent_beta_steps": { omit: ["changed_at"] },
  "public.agent_controls": { omit: ["id", "set_at"] },
  "public.agent_spend_limits": { omit: ["changed_at"] },
  "public.policy_announcements": { omit: ["announced_at"] },
  "public.settlement_settings": { omit: ["updated_at"] },
};

