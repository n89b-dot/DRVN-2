#!/usr/bin/env bash
# Plan 2 item A6 (N1075, N786): the stack-build proof of the baseline.
# Run by .github/workflows/baseline-proof.yml (started by hand), never by a
# push or a pull request. docs/plans/2026-11-a6-baseline-analysis.md section 5
# says why a stack build is proven apart from the guard build: real Storage and
# Auth tables, and the files applied by the Supabase CLI as `postgres`, not as
# `supabase_admin`.
#
#   PROOF_OUT=<dir> bash scripts/baseline/stack-proof.sh
#
# In order, stopping at the first that fails:
#   A. a local stack (`supabase start`, CLI 2.116.0) built from the files the
#      baseline replaces (supabase/migrations-archive/), captured with
#      scripts/baseline/compare.sh, then stopped and its volume removed
#   B. a local stack built from supabase/migrations/ (the baseline alone),
#      captured the same way
#   1. the four comparisons of A and B are empty
#   2. may `postgres` revoke on schema public from pg_database_owner? Asked on
#      B, in a transaction that is rolled back; the answer is written to
#      $PROOF_OUT/revoke-answer.txt, and "may not" fails this run
#   3. the whole browser suite on B (every project, first attempt only)
#   4. the Stripe test-mode lane on B, when STRIPE_SECRET_KEY is set. This
#      workflow reads no secret, so here it says it did not run; the lane runs
#      on the baseline's stack in ci.yml's stripe-integration job on the A6
#      pull request, whose supabase/migrations/ holds only the baseline.
#
# Needs a GitHub Actions runner (scripts/prepare-ci-supabase.mjs writes the
# stack's keys to $GITHUB_ENV), Docker, psql and pg_dump 17. Changes nothing
# outside the runner.
set -uo pipefail

root="$(cd "$(dirname "$0")/../.." && pwd)"
out="${PROOF_OUT:?PROOF_OUT: the folder the evidence is kept in}"
cli="supabase@2.116.0"
url="postgresql://postgres:postgres@127.0.0.1:54322/postgres"
# The browser suite's stack (the e2e job's exclusions): Realtime runs.
exclude="logflare,vector,studio,edge-runtime,imgproxy"
mkdir -p "$out"
cd "$root" || exit 2

step() { printf '\n== %s\n' "$*" | tee -a "$out/summary.txt"; }
note() { printf '%s\n' "$*" | tee -a "$out/summary.txt"; }
fail() { printf 'stack-proof: %s\n' "$*" | tee -a "$out/summary.txt" >&2; exit 1; }

# pg_dump must be 17 to read a Postgres 17 stack; the runner image carries 16.
if ! pg_dump --version 2>/dev/null | grep -q ' 17\.'; then
  if [ ! -x /usr/lib/postgresql/17/bin/pg_dump ]; then
    {
      sudo install -d /usr/share/postgresql-common/pgdg &&
      sudo curl -fsSL -o /usr/share/postgresql-common/pgdg/apt.postgresql.org.asc https://www.postgresql.org/media/keys/ACCC4CF8.asc &&
      echo "deb [signed-by=/usr/share/postgresql-common/pgdg/apt.postgresql.org.asc] https://apt.postgresql.org/pub/repos/apt $(. /etc/os-release && echo "$VERSION_CODENAME")-pgdg main" | sudo tee /etc/apt/sources.list.d/pgdg.list >/dev/null &&
      sudo apt-get update -q && sudo apt-get install -y -q postgresql-client-17
    } >"$out/pg-client-install.log" 2>&1 || { tail -20 "$out/pg-client-install.log"; fail "could not install the Postgres 17 client"; }
  fi
  export PATH="/usr/lib/postgresql/17/bin:$PATH"
fi
note "$(pg_dump --version)"

[ -d supabase/migrations-archive ] || fail "no supabase/migrations-archive/: this branch has not moved the history yet"
mapfile -t current < <(find supabase/migrations -maxdepth 1 -name '*.sql' | sort)
[ "${#current[@]}" -eq 1 ] || fail "supabase/migrations/ must hold exactly the baseline (it holds ${#current[@]} files)"
baseline="${current[0]}"
grep -q -- '-- DRVN baseline. Generated by scripts/baseline/build-baseline.mjs' "$baseline" || fail "$baseline is not marked as a baseline"
archived=$(find supabase/migrations-archive -maxdepth 1 -name '*.sql' | wc -l | tr -d ' ')
note "Baseline: $baseline ($(shasum -a 256 "$baseline" | cut -c1-16)); history: $archived files in supabase/migrations-archive/"

stage="$(mktemp -d)"
cp "$baseline" "$stage/"
restore() { rm -f supabase/migrations/*.sql; cp "$stage"/*.sql supabase/migrations/; }
trap restore EXIT

start_stack() { # label
  bash scripts/ci-supabase-start.sh "$exclude" >"$out/start-$1.log" 2>&1 || { tail -60 "$out/start-$1.log"; fail "stack $1 did not start (see start-$1.log)"; }
  tail -3 "$out/start-$1.log"
}
stop_stack() {
  npx --yes "$cli" stop --no-backup >>"$out/stop.log" 2>&1 || fail "the stack did not stop"
}

step "A: a stack from the $archived files the baseline replaces"
rm -f supabase/migrations/*.sql
cp supabase/migrations-archive/*.sql supabase/migrations/
start_stack A
bash scripts/baseline/compare.sh capture "$url" "$out/A" | tee -a "$out/summary.txt"
[ "${PIPESTATUS[0]}" -eq 0 ] || fail "could not capture stack A"
stop_stack

step "B: a stack from the baseline alone"
restore
start_stack B
bash scripts/baseline/compare.sh capture "$url" "$out/B" | tee -a "$out/summary.txt"
[ "${PIPESTATUS[0]}" -eq 0 ] || fail "could not capture stack B"

step "1. Is stack B the stack A?"
bash scripts/baseline/compare.sh compare "$out/A" "$out/B" | tee -a "$out/summary.txt"
[ "${PIPESTATUS[0]}" -eq 0 ] || fail "stack A and stack B differ (the diffs are in B/)"

step "2. May postgres revoke on schema public from pg_database_owner?"
# A non-owner's REVOKE without the grant option is not an error: PostgreSQL
# warns and changes nothing. So the answer is read from the ACL itself, before
# and after, inside a transaction that is rolled back.
psql "$url" -X -At -v ON_ERROR_STOP=1 >"$out/revoke.txt" 2>"$out/revoke.err" <<'SQL'
select 'user', current_user, (select rolsuper from pg_roles where rolname = current_user);
select 'owner of public', nspowner::regrole::text from pg_namespace where nspname = 'public';
select 'before', coalesce(nspacl::text, '(default)') from pg_namespace where nspname = 'public';
begin;
revoke all on schema public from pg_database_owner;
select 'after', coalesce(nspacl::text, '(default)') from pg_namespace where nspname = 'public';
rollback;
select 'after rollback', coalesce(nspacl::text, '(default)') from pg_namespace where nspname = 'public';
SQL
status=$?
cat "$out/revoke.txt" "$out/revoke.err"
before=$(awk -F'|' '$1=="before"{print $2}' "$out/revoke.txt")
after=$(awk -F'|' '$1=="after"{print $2}' "$out/revoke.txt")
if [ "$status" -ne 0 ]; then
  answer="may not: the revoke failed with an error (revoke.err)"
elif [ -n "$before" ] && [ "$before" != "$after" ]; then
  answer="may: the ACL of schema public changed from $before to $after (rolled back)"
elif ! printf '%s' "$before" | grep -q 'pg_database_owner='; then
  answer="nothing to revoke: pg_database_owner holds no grant on schema public on this stack ($before)"
else
  answer="may not: the revoke changed nothing ($before)$(grep -q WARNING "$out/revoke.err" && printf '; PostgreSQL warned: %s' "$(grep WARNING "$out/revoke.err" | head -1)")"
fi
printf '%s\n' "$answer" >"$out/revoke-answer.txt"
note "postgres $answer"
case "$answer" in "may not"*) fail "postgres may not revoke on schema public from pg_database_owner: tell the lead before changing the generator" ;; esac

step "3. The browser suite on stack B"
GITHUB_ENV="$stage/env" node scripts/prepare-ci-supabase.mjs >/dev/null || fail "could not prepare stack B for the browser suite"
set -a; # shellcheck disable=SC1091
. "$stage/env"; set +a
npx playwright install --with-deps >"$out/playwright-install.log" 2>&1 || { tail -30 "$out/playwright-install.log"; fail "could not install the browsers"; }
PAYMENTS_MODE=stub PAYMENTS_ALLOW_STUB_IN_PRODUCTION=true E2E_DIAGNOSTIC_RETRIES=0 \
  npm run test:e2e >"$out/e2e.log" 2>&1; e2e=$?
cp -R test-results "$out/e2e-results" 2>/dev/null || true
tail -15 "$out/e2e.log" | tee -a "$out/summary.txt"
[ "$e2e" -eq 0 ] || fail "the browser suite failed on the baseline's stack (e2e.log)"

step "4. The Stripe test-mode lane on stack B"
if [ -n "${STRIPE_SECRET_KEY:-}" ]; then
  npm run test:stripe >"$out/stripe.log" 2>&1; stripe=$?
  tail -10 "$out/stripe.log" | tee -a "$out/summary.txt"
  [ "$stripe" -eq 0 ] || fail "the Stripe lane failed on the baseline's stack (stripe.log)"
else
  note "Not run here: this workflow reads no secret. ci.yml's stripe-integration job runs it on the A6 pull request, on a stack built from the baseline alone."
fi

printf '\nProven on the stack build. Evidence kept in %s\n' "$out" | tee -a "$out/summary.txt"
