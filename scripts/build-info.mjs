// Writes src/lib/build-info.generated.ts: what /api/version reports about the
// code that was built, baked into the bundle so the route reads no files for
// it (docs/ids.md). Today that is the newest file in supabase/migrations/.
//
//   npm run build-info            rewrite the module
//   node scripts/build-info.mjs --check   exit 1 if it is stale
//
// tests/ci/build-info.test.ts runs the check in `npm test`, so a PR that adds
// a migration and forgets this fails with the one command to run.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export const BUILD_INFO_MODULE = "src/lib/build-info.generated.ts";

export function newestMigration(fileNames) {
  return fileNames.filter((name) => /^(\d{4}|\d{14})_[a-z0-9_]+\.sql$/.test(name)).sort().at(-1) ?? null;
}

export function buildInfoModule(fileNames) {
  return [
    "// Generated by `npm run build-info` (scripts/build-info.mjs). Do not edit.",
    "// tests/ci/build-info.test.ts fails when this is stale.",
    `export const NEWEST_MIGRATION_ON_DISK: string | null = ${JSON.stringify(newestMigration(fileNames))};`,
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = buildInfoModule(readdirSync("supabase/migrations"));
  if (process.argv.includes("--check")) {
    if (readFileSync(BUILD_INFO_MODULE, "utf8") !== text) {
      console.error(`${BUILD_INFO_MODULE} is stale: run \`npm run build-info\``);
      process.exit(1);
    }
  } else {
    writeFileSync(BUILD_INFO_MODULE, text);
    console.log(`wrote ${BUILD_INFO_MODULE}`);
  }
}
